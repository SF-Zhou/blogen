//! `blogen init` – create a new site skeleton.

use std::path::{Path, PathBuf};

use crate::error::{Error, IoContext, Result};

/// Options for [`init`].
#[derive(Debug, Clone)]
pub struct InitOptions {
    /// Target directory (created when missing).
    pub dir: PathBuf,
    /// Site name; defaults to the directory name.
    pub name: Option<String>,
    /// Canonical site URL.
    pub url: Option<String>,
    /// Overwrite existing files.
    pub force: bool,
    /// Create the example article.
    pub example: bool,
}

impl Default for InitOptions {
    fn default() -> Self {
        Self {
            dir: PathBuf::from("."),
            name: None,
            url: None,
            force: false,
            example: true,
        }
    }
}

/// Create a new site skeleton.
///
/// Returns the list of created files (relative to `dir`).
pub fn init(options: &InitOptions) -> Result<Vec<PathBuf>> {
    let dir = &options.dir;
    std::fs::create_dir_all(dir)
        .with_context(|| format!("creating site directory `{}`", dir.display()))?;

    let site_name = options.name.clone().unwrap_or_else(|| {
        std::fs::canonicalize(dir)
            .ok()
            .and_then(|path| {
                path.file_name()
                    .map(|name| name.to_string_lossy().to_string())
            })
            .filter(|name| !name.is_empty() && name != ".")
            .unwrap_or_else(|| "My Blog".to_string())
    });
    let site_url = options
        .url
        .clone()
        .unwrap_or_else(|| "https://example.com".to_string());
    let config_path = dir.join("blogen.toml");
    if config_path.exists() && !options.force {
        return Err(Error::Cli(format!(
            "`{}` already exists; use `--force` to overwrite it",
            config_path.display()
        )));
    }

    let mut created = Vec::new();
    write_file(
        &config_path,
        &config_template(&site_name, &site_url),
        &mut created,
    )?;

    let posts_dir = dir.join("posts");
    std::fs::create_dir_all(&posts_dir)
        .with_context(|| format!("creating posts directory `{}`", posts_dir.display()))?;
    if options.example {
        let example_path = posts_dir.join("[2026.01.01 Hello]hello-world.md");
        if !example_path.exists() || options.force {
            write_file(&example_path, EXAMPLE_ARTICLE, &mut created)?;
        }
    }
    let readme_path = dir.join("README.md");
    if !readme_path.exists() || options.force {
        write_file(&readme_path, &readme_template(&site_name), &mut created)?;
    }
    Ok(created)
}

fn write_file(path: &Path, contents: &str, created: &mut Vec<PathBuf>) -> Result<()> {
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent)
            .with_context(|| format!("creating directory `{}`", parent.display()))?;
    }
    std::fs::write(path, contents).with_context(|| format!("writing `{}`", path.display()))?;
    created.push(path.to_path_buf());
    Ok(())
}

fn config_template(site_name: &str, site_url: &str) -> String {
    format!(
        r#"# blogen configuration – see https://github.com/SF-Zhou/blogen/blob/main/docs/config-reference.md
[site]
name = "{site_name}"
url = "{site_url}"
description = "{site_name}"
language = "en"
default_author = "Your Name"
web_master = "Your Name"
# google_analytics_id = "G-XXXXXXXXXX"
# base_path = "/"

[build]
posts = "posts"
output = "public"
article_format = "md"

[theme]
name = "default"

# Uncomment to generate a profile README:
# [profile]
# path = "profile"
# limit = 5

# Uncomment to enable giscus comments:
# [comments.giscus]
# repo = "owner/repo"
# repo_id = "R_xxxxxxxx"
# category = "Announcements"
# category_id = "DIC_xxxxxxxx"
"#
    )
}

fn readme_template(site_name: &str) -> String {
    format!(
        r"# {site_name}

A static blog built with [blogen](https://github.com/SF-Zhou/blogen).

## Usage

```bash
# preview at http://127.0.0.1:9000
blogen serve

# build into ./public
blogen build
```

Articles live in `posts/`. The file name carries the metadata:

```text
posts/[2026.01.01 Rust,Tutorial Your Name]my-post.md
```

The first `# heading` in the file becomes the article title.
"
    )
}

