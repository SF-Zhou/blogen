#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn creates_site_skeleton() {
        let temp = tempfile::tempdir().unwrap();
        let dir = temp.path().join("myblog");
        let created = init(&InitOptions {
            dir: dir.clone(),
            name: Some("My Blog".into()),
            url: Some("https://myblog.example".into()),
            ..Default::default()
        })
        .unwrap();
        assert!(created.iter().any(|p| p.ends_with("blogen.toml")));
        let config = std::fs::read_to_string(dir.join("blogen.toml")).unwrap();
        assert!(config.contains("name = \"My Blog\""));
        assert!(config.contains("url = \"https://myblog.example\""));
        assert!(dir.join("posts/[2026.01.01 Hello]hello-world.md").is_file());
    }

    #[test]
    fn refuses_to_overwrite_without_force() {
        let temp = tempfile::tempdir().unwrap();
        let options = InitOptions {
            dir: temp.path().to_path_buf(),
            ..Default::default()
        };
        init(&options).unwrap();
        let err = init(&options).unwrap_err();
        assert!(matches!(err, Error::Cli(_)));
        init(&InitOptions {
            force: true,
            ..options
        })
        .unwrap();
    }
}
